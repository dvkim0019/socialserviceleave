/**
 * 주어진 날짜가 법정 공휴일인지 확인
 */
export function isKoreanHoliday(dateStr: string): boolean {
  return Boolean(KOREAN_HOLIDAYS[dateStr]);
}

/**
 * 주어진 날짜가 근무일(평일 & 공휴일 아님)인지 확인
 */
export function isWorkingDay(date: Date, checkHoliday: boolean = true): boolean {
  const dayOfWeek = date.getDay(); // 0 = 일요일, 6 = 토요일
  if (dayOfWeek === 0 || dayOfWeek === 6) {
    return false;
  }
  if (!checkHoliday) {
    return true;
  }
  const dateStr = formatDate(date);
  return !isKoreanHoliday(dateStr);
}

export function formatDate(d: Date): string {
  const yyyy = d.getFullYear();
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  const dd = String(d.getDate()).padStart(2, '0');
  return `${yyyy}-${mm}-${dd}`;
}

export function parseDate(dateStr: string): Date {
  const [y, m, d] = dateStr.split('-').map(Number);
  return new Date(y, m - 1, d);
}
